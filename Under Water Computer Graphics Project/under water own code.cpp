void handleKeypress(unsigned char key, int x, int y) {
    switch (key) {
        // Robot Movement Controls
        case 's':
        case 'S':
            posY += moveSpeed;
            break;
        case 'x':
        case 'X':
            posY -= moveSpeed;
            break;
        case 'z':
        case 'Z':
            posX -= moveSpeed;
            break;
        case 'c':
        case 'C':
            posX += moveSpeed;
            break;

        // Light Beam Controls
        case 'n':
        case 'N':
            showLightBeam = true;
            break;
        case 'f':
        case 'F':
            showLightBeam = false;
            break;

        // Day / Night Controls
        case 'a':
        case 'A':
            isNight = false; // Day Mode
            break;

        case 'k':
        case 'K':
            isNight = true;  // Night Mode
            break;
    }

    glutPostRedisplay(); // switch শেষ হওয়ার পর একবার কল করলেই সব কেসের জন্য কাজ করবে
}


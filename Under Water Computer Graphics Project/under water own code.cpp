/* Helper function to draw smooth black dots on the body */
void drawBodyDot(float cx, float cy, float rx, float ry) {
    glBegin(GL_TRIANGLE_FAN);
        glColor3f(0.12f, 0.08f, 0.05f);
        glVertex2f(cx, cy);
        for (int i = 0; i <= 14; ++i) {
            float angle = i * 2.0f * 3.14159265f / 14;
            glVertex2f(cx + cosf(angle) * rx, cy + sinf(angle) * ry);
        }
    glEnd();
}


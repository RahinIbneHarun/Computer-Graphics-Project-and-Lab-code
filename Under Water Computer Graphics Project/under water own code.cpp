void animatedFish() {
    glMatrixMode(GL_MODELVIEW);
    glPushMatrix();

    // isHovered সত্য হলে ১.৫ গুণ বড় হবে, না হলে ১.০ থাকবে
    float s = isHovered ? 1.5f : 1.0f;

    // মাছের পজিশন ও স্কেলিং
    glTranslatef(_move + fishCenterX * (1.0f - s), fishCenterY * (1.0f - s), 0.0f);
    glScalef(s, s, 1.0f);

    drawFish();
    glPopMatrix();
}
void mousePassive(int x, int y) {
    // উইন্ডো পিক্সেলকে ওয়ার্ল্ড কোঅর্ডিনেটে রূপান্তর (Ortho 0 থেকে 18.5 এবং 0 থেকে 10.5 অনুযায়ী)
    float mouseX = ((float)x / windowWidth) * 18.5f;
    float mouseY = 10.5f - ((float)y / windowHeight) * 10.5f;

    // মাছের বর্তমান সঠিক কেন্দ্র (মুভমেন্ট সহ)
    float cx = fishCenterX + _move;
    float cy = fishCenterY;

    // মাছের চারপাশে একটি সহজ ক্লিক বা হোভার বক্স (Bounding Box) তৈরি করা
    float boxSize = 1.2f; // মাছের সাইজ অনুযায়ী এলাকা

    if (mouseX >= (cx - boxSize) && mouseX <= (cx + boxSize) &&
        mouseY >= (cy - boxSize) && mouseY <= (cy + boxSize)) {
        isHovered = true;
    } else {
        isHovered = false;
    }

    glutPostRedisplay();
}

void updateFish(int (value)) {
    _move -= 0.015f; // মাছটি বাম দিকে যাওয়ার গতি

    // মাছটি যদি বাম দিক দিয়ে স্ক্রিনের বাইরে চলে যায় (-18.0 এর নিচে)
    if (_move < -18.0f) {
        _move = 5.0f; // এটি একেবারে ডান দিক থেকে নতুন করে শুরু করবে
    }

    glutPostRedisplay();
    glutTimerFunc(20, updateFish, 0);
}

void reshape(int w, int h) {
    windowWidth = w;   // উইন্ডোর নতুন চওড়া আপডেট হবে
    windowHeight = h;  // উইন্ডোর নতুন উচ্চতা আপডেট হবে
    glViewport(0, 0, w, h);
}


void update(int value) {
if (isTransitioning) {
sunX -= sunSpeed;
if (sunX <= -2.0f) {
isTransitioning = false;
isDay = false;
sunX = 15.0f;
}
}
glutPostRedisplay();
glutTimerFunc(30, update, 0);
}
void handleMouse(int button, int state, int x, int y) {if (button == GLUT_LEFT_BUTTON && state == GLUT_DOWN) {
if (isDay && !isTransitioning) {
isTransitioning = true;
}
}
}
void handleKeypress(unsigned char key, int x, int y) {
switch (key) {
case 'd':
case 'D':
isDay = true;
isTransitioning = false;
sunX = 15.0f;
break;
case 'n':
case 'N':
isDay = false;
isTransitioning = false;
break;
case ' ':
if (isDay && !isTransitioning) {
isTransitioning = true;
} else if (!isDay) {
isDay = true;
sunX = 15.0f;
}
break;
}
glutPostRedisplay();
}
void initGL() {
glMatrixMode(GL_PROJECTION);
glLoadIdentity();
gluOrtho2D(-2.0, 20.0, 0.0, 18.0);
}
void display() {
if (isDay) {
renderDayScene();
} else {
renderNightScene();
}}
int main(int argc, char** argv) { glutInit(&argc, argv); glutInitDisplayMode(GLUT_SINGLE | GLUT_RGB); glutInitWindowSize(800, 600); glutInitWindowPosition(100, 100); glutCreateWindow("Interactive Day to Night Scene");
initGL(); glutDisplayFunc(display); glutMouseFunc(handleMouse); glutKeyboardFunc(handleKeypress); glutTimerFunc(30, update, 0);
glutMainLoop(); return 0;
}